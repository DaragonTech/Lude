local ctest = require "ctest"
print("fmt", ctest.fmt("arg"))
print("fmtptr", ctest.fmtptr())
print("error", pcall(ctest.error))
local ok, e = pcall(ctest.errtable) print("errtable", ok, type(e), e.code)
print("buffer", #ctest.buffer(2000), ctest.buffer(30))
print("where", ctest.where())
local p = ctest.newpoint(2.25, 7)
print("point", ctest.pointinfo(p))
print("pointerr", pcall(ctest.pointinfo, {}))
print("cpcall", ctest.cpcall())
print("pcallerr", ctest.pcallerr(function() error("lua err") end))
local co = coroutine.create(function(a) local x, y = ctest.yield() return a + x + y end)
print("yield", coroutine.resume(co, 1))
print("resume", coroutine.resume(co))
print("ref", ctest.ref())
print("misc", ctest.misc())
print("gsub", ctest.gsub("banana"))
-- error thrown by C inside nested pcall inside coroutine
local co2 = coroutine.wrap(function() return pcall(ctest.error) end)
print("co+pcall", co2())
-- xpcall with traceback through a C function
print("xpcall", select(2, xpcall(ctest.error, debug.traceback)):gsub("\n.*", ""))
print("done")

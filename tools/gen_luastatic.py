#!/usr/bin/env python3
"""Generates src/LuaStatic.pas from src/LuaDLL.pas.

LuaStatic has the same interface as LuaDLL (constants, types, functions,
macros) but calls the statically linked Pascal units instead of importing
lua5.1.dll.  Run it again whenever LuaDLL.pas changes:
    python3 tools/gen_luastatic.py
"""
import re, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')
dll = open(os.path.join(SRC, 'LuaDLL.pas')).read()

# where each internal routine lives (interface section of a core/library unit)
units = ['LuaAPI', 'LuaAuxLib', 'LuaState', 'LuaDo', 'LuaDebug', 'LuaInit', 'LuaBaseLib',
         'LuaTabLib', 'LuaIOLib', 'LuaOSLib', 'LuaStrLib', 'LuaMathLib', 'LuaDbLib', 'LuaLoadLib']
home = {}
for u in units:
    t = open(os.path.join(SRC, u + '.pas')).read()
    intf = t[:re.search(r'^implementation\b', t, re.M).start()]
    for m in re.finditer(r'^\s*(?:function|procedure)\s+(\w+)', intf, re.M):
        home.setdefault(m.group(1), u)

head, rest = dll.split('{ lua.h }', 1)
decls, macros = rest.split('{ macros from lua.h / lauxlib.h }', 1)
macro_intf, macro_impl = macros.split('implementation', 1)
macro_impl = macro_impl.rsplit('end.', 1)[0]
# skip LuaDLL's own helpers (va_list builder etc.): keep only the macro bodies
macro_impl = '\n' + macro_impl[macro_impl.index('function lua_upvalueindex'):]

# constants: everything between "const" and "type" except the DLL name
consts = head[re.search(r'^const\b', head, re.M).start():head.index('\ntype')]
consts = re.sub(r'\{\$IFDEF LUA_USE_LUA51\}.*?\{\$ENDIF\}\n', '', consts, flags=re.S)

intf_lines, impl_lines = [], []
section = '{ lua.h }'
for ln in ('{ lua.h }' + decls).split('\n'):
    s = ln.strip()
    if s.startswith('{ ') and s.endswith('}'):
        intf_lines.append('\n' + s); continue
    m = re.match(r'(function|procedure)\s+(\w+)(\(([^)]*)\))?\s*(:\s*(\w+))?;\s*cdecl;(\s*varargs;)?\s*external', s)
    if not m: continue
    kind, name, _, params, _, ret, varargs = m.groups()
    if varargs:
        continue  # C varargs cannot be declared for non-external routines; see *f variants
    unit = home[name]
    names = []
    if params:
        for grp in params.split(';'):
            ids = grp.split(':')[0]
            names += [x.strip() for x in ids.split(',')]
    call = f"{unit}.{name}" + (f"({', '.join(names)})" if names else '')
    sig = f"{kind} {name}" + (f"({params})" if params else '') + (f": {ret}" if ret else '') + ';'
    intf_lines.append(sig + ' inline;')
    body = f"Result := {call};" if kind == 'function' else f"{call};"
    impl_lines.append(f"{sig} begin {body} end;")

out = f"""(*
  Lua 5.1.4 - Pascal port: static-linking unit.

  Same interface as LuaDLL.pas (constants, types, the lua.h / lauxlib.h /
  lualib.h functions and macros), but Lua is compiled into the program
  instead of being imported from lua5.1.dll.  Code written against LuaDLL
  compiles unchanged with LuaStatic, e.g.

    uses {{$IFDEF LUA_STATIC}} LuaStatic {{$ELSE}} LuaDLL {{$ENDIF}};

  Differences from LuaDLL:
  - lua_pushfstring and luaL_error with C-style varargs exist only in
    LuaDLL (Pascal can declare varargs for DLL imports only).  Use
    lua_pushfstringf / luaL_errorf, which take an array of const and are
    available in both units:  luaL_errorf(L, 'bad value %d', [n]);
  - C extension modules (DLLs linked to lua5.1.dll) cannot be loaded by
    a program that links Lua statically.

  GENERATED by tools/gen_luastatic.py from LuaDLL.pas - do not edit by hand.
*)
unit LuaStatic;

{{$I lua.inc}}

interface

uses
  LuaTypes, LuaFPU, LuaAPI, LuaAuxLib, LuaState, LuaDo, LuaDebug, LuaInit,
  LuaBaseLib, LuaTabLib, LuaIOLib, LuaOSLib, LuaStrLib, LuaMathLib, LuaDbLib, LuaLoadLib;

{consts.rstrip()}

type
  size_t = LuaTypes.size_t;
  Psize_t = LuaTypes.Psize_t;
  lua_Number = LuaTypes.lua_Number;
  lua_Integer = LuaTypes.lua_Integer;
  Plua_State = LuaTypes.Plua_State;
  Plua_Debug = LuaTypes.Plua_Debug;
  lua_CFunction = LuaTypes.lua_CFunction;
  lua_Reader = LuaTypes.lua_Reader;
  lua_Writer = LuaTypes.lua_Writer;
  lua_Alloc = LuaTypes.lua_Alloc;
  lua_Hook = LuaTypes.lua_Hook;
  lua_Debug = LuaTypes.lua_Debug;
  PluaL_Reg = LuaTypes.PluaL_Reg;
  luaL_Reg = LuaTypes.luaL_Reg;
  PluaL_Buffer = LuaTypes.PluaL_Buffer;
  luaL_Buffer = LuaTypes.luaL_Buffer;
{chr(10).join(intf_lines)}

{{ formatted messages with a Pascal array of const (%d %f %s %p %c %%) }}
function lua_pushfstringf(L: Plua_State; fmt: PAnsiChar; const args: array of const): PAnsiChar;
function luaL_errorf(L: Plua_State; fmt: PAnsiChar; const args: array of const): Integer;

{{ puts the FPU in the state a C program has (all FP exceptions masked);
  call once at startup so 0/0 and 1/0 give NaN/inf instead of raising }}
procedure lua_set_c_fpu_mode;

{{ macros from lua.h / lauxlib.h }}{macro_intf.rstrip()}

implementation

{chr(10).join(impl_lines)}

function lua_pushfstringf(L: Plua_State; fmt: PAnsiChar; const args: array of const): PAnsiChar;
begin
  Result := LuaAuxLib.lua_pushfstringf(L, fmt, args);
end;

function luaL_errorf(L: Plua_State; fmt: PAnsiChar; const args: array of const): Integer;
begin
  Result := LuaAuxLib.luaL_errorf(L, fmt, args);
end;

procedure lua_set_c_fpu_mode;
begin
  LuaFPU.lua_set_c_fpu_mode;
end;
{macro_impl.rstrip()}

end.
"""
open(os.path.join(SRC, 'LuaStatic.pas'), 'w', newline='\r\n').write(out)
print('wrote src/LuaStatic.pas:', len(impl_lines), 'API functions')

#!/usr/bin/env python3
"""Generates the files for the "hybrid" setup (Lua linked into the program,
C modules still loadable):

  src/LuaHostExports.pas  - unit that makes the program export the C API
  hybrid/lua5.dpr         - shim lua5.1.dll whose exports jump into the
                            module (normally the EXE) that exports the API
  src/luaapi.dynlist      - linker dynamic list for Linux executables
  src/luaapi.exp          - exported symbols list for macOS executables

Run again if exports.txt changes:  python3 tools/gen_hybrid.py
"""
import re, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')
names = open(os.path.join(ROOT, 'exports.txt')).read().split()

units = ['LuaAPI', 'LuaAuxLib', 'LuaState', 'LuaDo', 'LuaDebug', 'LuaInit', 'LuaBaseLib',
         'LuaTabLib', 'LuaIOLib', 'LuaOSLib', 'LuaStrLib', 'LuaMathLib', 'LuaDbLib', 'LuaLoadLib']
home = {}
for u in units:
    t = open(os.path.join(SRC, u + '.pas')).read()
    intf = t[:re.search(r'^implementation\b', t, re.M).start()]
    for m in re.finditer(r'^\s*(?:function|procedure)\s+(\w+)', intf, re.M):
        home.setdefault(m.group(1), u)
missing = [n for n in names if n not in home]
assert not missing, missing

# ---------------------------------------------------------------- exports unit
exp = ',\n'.join(f"  {home[n]}.{n} name '{n}'" for n in names)
posix_wr = '\n'.join(
    f"procedure x_{n}; assembler; nostackframe; public name CPREFIX + '{n}';\nasm\n  {{$IFDEF CPUAARCH64}}b{{$ELSE}}jmp{{$ENDIF}} {n}\nend;\n"
    for n in names)
dynlist = "{\n" + "".join(f"  {n};\n" for n in names) + "};\n"
open(os.path.join(SRC, 'luaapi.dynlist'), 'w').write(dynlist)
# macOS: -exported_symbols_list (C names carry a leading underscore)
open(os.path.join(SRC, 'luaapi.exp'), 'w').write("".join(f"_{n}\n" for n in names))
unit = f"""{{
  Lua 5.1.4 - Pascal port: makes the program export the Lua C API.

  Add this unit to the uses clause of a program that links Lua statically
  (LuaStatic).  The executable then exports the same {len(names)} functions as
  lua5.1.dll, and the shim lua5.1.dll built from hybrid/lua5.dpr forwards
  C extension modules (require "foo" -> foo.dll) to the Lua inside the
  program, so they share its lua_State.

  GENERATED by tools/gen_hybrid.py - do not edit by hand.
}}
unit LuaHostExports;

{{$I lua.inc}}

interface

implementation

uses
  {', '.join(units)};

{{$IF defined(FPC) and not defined(MSWINDOWS)}}
{{ Free Pascal on Linux/Unix/macOS ignores 'exports' in a program: give each
  API function a global C-named alias instead (a jump to the Pascal routine).
  Linux: link with  -k--dynamic-list=src/luaapi.dynlist  so the executable's
  dynamic symbol table contains exactly these names (like -Wl,-E).
  macOS: link with  -k-exported_symbols_list -ksrc/luaapi.exp . }}
const
  CPREFIX = {{$IFDEF DARWIN}}'_'{{$ELSE}}''{{$ENDIF}};   {{ C symbol prefix }}

{posix_wr}
{{$ELSE}}
exports
{exp};
{{$IFEND}}

end.
"""
open(os.path.join(SRC, 'LuaHostExports.pas'), 'w', newline='\r\n').write(unit)

# ---------------------------------------------------------------- shim DLL
stubs = []
for i, n in enumerate(names):
    stubs.append(f"""procedure s_{n}; {{$IFDEF FPC}}assembler; nostackframe;{{$ENDIF}}
asm
{{$IFDEF LUA_64}}
  {{$IFDEF FPC}}
  jmp qword ptr [rip + Table + {8 * i}]
  {{$ELSE}}
  .NOFRAME
  jmp qword ptr [Table + {8 * i}]   {{ Delphi x64 addresses globals RIP-relative }}
  {{$ENDIF}}
{{$ELSE}}
  jmp dword ptr [Table + {4 * i}]
{{$ENDIF}}
end;
""")
namelist = ',\n'.join(f"    '{n}'" for n in names)
explist = ',\n'.join(f"  s_{n} name '{n}'" for n in names)
shim = f"""{{
  lua5.1.dll - HYBRID SHIM (not the Lua implementation).

  For programs that link Lua statically (LuaStatic) and add LuaHostExports:
  put this lua5.1.dll next to the program instead of the real one.  C
  extension modules linked against lua5.1.dll (or lua51.dll, through the
  proxy) then call the Lua inside the program.

  Each export is a jump through a table that is filled when the shim is
  loaded: the first loaded module (the EXE first) that exports
  luaL_newstate, other than this shim, provides the functions.

  Delphi: this project is named "lua5" and $LIBSUFFIX makes it lua5.1.dll;
  build it into a separate folder from the real lua5.1.dll.
  GENERATED by tools/gen_hybrid.py - do not edit by hand.
}}
library lua5;

{{$I lua.inc}}
{{$IFNDEF FPC}}
  {{$LIBSUFFIX '.1'}}
{{$ENDIF}}

const
  kernel32 = 'kernel32.dll';
  NAPI = {len(names)};
  TH32CS_SNAPMODULE = $00000008;
  STD_ERROR_HANDLE = Cardinal(-12);
  API_NAMES: array[0..NAPI - 1] of PAnsiChar = (
{namelist});

type
  TModuleEntry32 = record
    dwSize: Cardinal;
    th32ModuleID: Cardinal;
    th32ProcessID: Cardinal;
    GlblcntUsage: Cardinal;
    ProccntUsage: Cardinal;
    modBaseAddr: PByte;
    modBaseSize: Cardinal;
    hModule: NativeUInt;
    szModule: array[0..255] of AnsiChar;
    szExePath: array[0..259] of AnsiChar;
  end;

function GetModuleHandleA(name: PAnsiChar): NativeUInt; stdcall; external kernel32;
function GetProcAddress(h: NativeUInt; name: PAnsiChar): Pointer; stdcall; external kernel32;
function CreateToolhelp32Snapshot(flags, pid: Cardinal): NativeUInt; stdcall; external kernel32;
function Module32First(snap: NativeUInt; var me: TModuleEntry32): LongBool; stdcall; external kernel32;
function Module32Next(snap: NativeUInt; var me: TModuleEntry32): LongBool; stdcall; external kernel32;
function CloseHandle(h: NativeUInt): LongBool; stdcall; external kernel32;
function GetStdHandle(n: Cardinal): NativeUInt; stdcall; external kernel32;
function WriteFile(h: NativeUInt; buf: Pointer; n: Cardinal; written: PCardinal; ov: Pointer): LongBool; stdcall; external kernel32;
procedure ExitProcess(code: Cardinal); stdcall; external kernel32;

var
  Table: array[0..NAPI - 1] of Pointer;

procedure no_host;
const MSG: PAnsiChar = 'lua5.1.dll (hybrid shim): no module in this process exports the Lua API.'#13#10 +
  'Link Lua into the program with LuaStatic and add the LuaHostExports unit.'#13#10;
var w: Cardinal; n: Integer;
begin
  n := 0;
  while MSG[n] <> #0 do Inc(n);
  WriteFile(GetStdHandle(STD_ERROR_HANDLE), MSG, n, @w, nil);
  ExitProcess(3);
end;

function find_host: NativeUInt;
var snap: NativeUInt; me: TModuleEntry32; self_: NativeUInt;
begin
  self_ := HInstance;
  Result := GetModuleHandleA(nil);   {{ the EXE first }}
  if GetProcAddress(Result, 'luaL_newstate') <> nil then Exit;
  Result := 0;
  snap := CreateToolhelp32Snapshot(TH32CS_SNAPMODULE, 0);
  if (snap = 0) or (snap = NativeUInt(-1)) then Exit;
  FillChar(me, SizeOf(me), 0);
  me.dwSize := SizeOf(me);
  if Module32First(snap, me) then
    repeat
      if (me.hModule <> self_) and (GetProcAddress(me.hModule, 'luaL_newstate') <> nil) then
      begin
        Result := me.hModule;
        Break;
      end;
    until not Module32Next(snap, me);
  CloseHandle(snap);
end;

{chr(10).join(stubs)}
exports
{explist};

{{ Fills one table entry.  Kept out of the loop, and unoptimised, on
  purpose: Delphi 10.2's Win64 compiler turned the original loop (reading
  API_NAMES[i], writing Table[i]) into two stepping pointers kept in ONE
  stack slot, so it looked names up from Table itself and left every other
  entry nil (crash on the first call from a C module). }}
{{$OPTIMIZATION OFF}}
procedure resolve(host: NativeUInt; i: Integer);
var p: Pointer;
begin
  p := nil;
  if host <> 0 then p := GetProcAddress(host, API_NAMES[i]);
  if p = nil then p := @no_host;
  Table[i] := p;
end;

procedure fill_table;
var host: NativeUInt; i: Integer;
begin
  host := find_host;
  i := 0;
  while i < NAPI do
  begin
    resolve(host, i);
    Inc(i);
  end;
end;
{{$OPTIMIZATION ON}}

begin
  fill_table;
end.
"""
os.makedirs(os.path.join(ROOT, 'hybrid'), exist_ok=True)
open(os.path.join(ROOT, 'hybrid', 'lua5.dpr'), 'w', newline='\r\n').write(shim)
print('wrote src/LuaHostExports.pas and hybrid/lua5.dpr for', len(names), 'functions')
